import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile, readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

test('registration and score review UI highlights changes and preserves save/download behavior', { skip: process.env.CEPT_REVIEW_BROWSER !== '1' }, async () => {
  const folder = await mkdtemp(fileURLToPath(new URL('./.cept-browser-review-', import.meta.url)));
  const root = fileURLToPath(new URL('../', import.meta.url));
  process.env.DATABASE_URL = `file:${path.join(folder, 'test.db').replaceAll('\\', '/')}`;
  process.env.BACKUP_DIR = path.join(folder, 'backups');
  await writeFile(path.join(folder, 'test.db'), '');
  let server, prisma, browser;
  try {
    execFileSync(process.execPath, [path.join(root, 'node_modules/prisma/build/index.js'), 'db', 'push', '--skip-generate', '--schema', path.join(root, 'prisma/schema.prisma')], { env: process.env, stdio: 'pipe' });
    ({ prisma } = await import('../src/db/connect.js'));
    const { default: app } = await import('../src/app.js');
    const { default: bcrypt } = await import('bcryptjs');
    const { default: XLSX } = await import('xlsx');
    const { chromium } = await import('playwright');
    await prisma.user.create({ data: { username: 'review-staff', role: 'user', password: await bcrypt.hash('fixture-password', 4) } });
    const names = ['Noor Hassan', 'Omar Nabil', 'Salma Adel', 'Youssef Wael', 'Mina Aziz', 'Laila Sami', 'Adam Tarek', 'Nadine Farid', 'Karim Ali', 'Sara Mostafa'];
    for (let i = 0; i < 7; i++) await prisma.student.create({ data: { registrationNumber: `00${120 + i}`, name: names[i], firstName: '', lastName: names[i], nameVerified: true, score: i < 4 ? 70 + i : null } });
    server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
    const errors = [], downloads = [];
    page.on('pageerror', error => errors.push(error.message)); page.on('download', download => downloads.push(download));
    await page.route('**/*', route => route.request().url().startsWith(base) || /^(data|blob):/.test(route.request().url()) ? route.continue() : route.abort());
    await page.addInitScript(() => { globalThis.showSaveFilePicker = undefined; });
    const capture = async name => { if (process.env.CEPT_REVIEW_ARTIFACT_DIR) { await mkdir(process.env.CEPT_REVIEW_ARTIFACT_DIR, { recursive: true }); await page.screenshot({ path: path.join(process.env.CEPT_REVIEW_ARTIFACT_DIR, name) }); } };
    await page.goto(base);
    await page.getByLabel('Username', { exact: true }).fill('review-staff'); await page.getByLabel('Password', { exact: true }).fill('fixture-password');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('link', { name: 'CEPT data' }).click();
    await page.getByRole('button', { name: 'Upload IDs', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Check registration IDs', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Choose files', exact: true }).isVisible(), true);
    const uploads = [[0, 7, 'Morning registrations.xlsx'], [7, 10, 'Afternoon registrations.xlsx']].map(([start, end, name]) => {
      const book = XLSX.utils.book_new();
      XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([['RegNum', 'Name', 'Email', 'Mobile', 'Date', 'Time', 'Department'], ...names.slice(start, end).map((name, offset) => [`00${120 + start + offset}`, name, `${name.split(' ')[0].toLowerCase()}@example.invalid`, '0100 123 4567', '28-10-2026', start === 0 ? '10:00 AM' : '1:00 PM', start === 0 ? 'Engineering' : 'Business'])]), 'Registrations');
      return { name, mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: XLSX.write(book, { type: 'buffer', bookType: 'xlsx' }) };
    });
    await page.getByRole('dialog').locator('input[type=file]').setInputFiles([...uploads, { ...uploads[0], name: 'Repeated registrations.xlsx' }]);
    await page.getByRole('button', { name: 'Keep this entry', exact: true }).first().waitFor();
    assert.equal(await page.getByRole('button', { name: 'Save batch', exact: true }).isDisabled(), true);
    assert.equal(await prisma.registrationBatch.count(), 0);
    for (let remaining = 7; remaining > 0; remaining--) {
      await page.getByRole('button', { name: 'Keep this entry', exact: true }).first().click();
      await page.getByRole('button', { name: 'Choose different files', exact: true }).waitFor();
      assert.equal(await page.locator('.review-table tr[data-duplicate=true]').count(), (remaining - 1) * 2);
    }
    await page.getByRole('button', { name: 'Save batch', exact: true }).waitFor();
    assert.equal(await page.locator('.review-table tbody tr[data-changed=true]').count(), 4);
    assert.equal(await page.locator('.review-id--changed strong').first().textContent(), '00120-R1');
    assert.equal(await page.locator('.review-id-before').first().textContent(), '00120');
    const changedBg = await page.locator('.review-table tbody tr[data-changed=true] td').first().evaluate(element => globalThis.getComputedStyle(element).backgroundColor);
    const normalBg = await page.locator('.review-table tbody tr:not([data-changed]) td').first().evaluate(element => globalThis.getComputedStyle(element).backgroundColor);
    assert.notEqual(changedBg, normalBg);
    await page.evaluate(() => globalThis.document.fonts.ready);
    await capture('cept-ids-review-dark.png');
    await page.getByRole('button', { name: 'Changed 4', exact: true }).click(); assert.equal(await page.locator('.review-table tbody tr').count(), 4);
    await page.getByRole('button', { name: 'Unchanged 6', exact: true }).click(); assert.equal(await page.locator('.review-table tbody tr').count(), 6);
    assert.equal(await page.locator('.review-file-heading h3').count(), 2);
    await page.getByRole('button', { name: 'Errors 0', exact: true }).click();
    await page.getByText('No rows match this view', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click(); assert.equal(await page.locator('.review-table tbody tr').count(), 10);
    await page.getByRole('textbox', { name: 'Search preview', exact: true }).fill('Sara'); assert.equal(await page.locator('.review-table tbody tr').count(), 1);
    await page.getByRole('textbox', { name: 'Search preview', exact: true }).fill('');
    assert.equal(await prisma.registrationBatch.count(), 0); assert.equal(await prisma.student.count({ where: { registrationNumber: '00120-R1' } }), 0);
    await page.getByRole('button', { name: 'Save batch', exact: true }).click();
    await page.getByRole('button', { name: 'Done', exact: true }).waitFor(); assert.equal(downloads.length, 0);
    assert.equal(await prisma.registrationBatch.count(), 1);
    await page.getByRole('button', { name: 'Done', exact: true }).click();
    await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
    await page.getByRole('button', { name: 'Upload Scores', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Check scores', exact: true }).waitFor();
    const csv = 'Textbox2,RSURN,RFIRST,TotalScore,TGVALUE\n00120-R1,Student,Written,85,B2\n00121-R1,Other,Alias,82,B2\n00124,Student,Name,65,B1\n00999-R9,Unknown,Student,55,A2\n';
    await page.getByRole('dialog').locator('input[type=file]').setInputFiles({ name: 'CEPT Group Report.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
    await page.getByRole('button', { name: 'Save 3 matched & download', exact: true }).waitFor();
    assert.equal(await page.locator('.review-table tbody tr[data-changed=true]').count(), 3);
    assert.equal(await page.locator('.review-table tbody tr[data-unmatched=true]').count(), 1);
    assert.equal(await page.locator('.review-id--changed strong').first().textContent(), '00120');
    await capture('cept-scores-review-light.png');
    await page.getByRole('button', { name: 'Errors 1', exact: true }).click(); assert.equal(await page.locator('.review-table tbody tr').count(), 1);
    assert.match(await page.locator('.review-table tbody').textContent(), /00999-R9/);
    await page.getByRole('button', { name: 'All 4', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    const bounds = await page.getByRole('dialog').boundingBox(); assert.ok(bounds.width <= 390 && bounds.height <= 844);
    const footer = await page.locator('.review-footer').boundingBox(); assert.ok(footer.y + footer.height <= 844);
    assert.equal(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth + 1), true);
    await page.locator('.review-body').evaluate(element => { element.scrollTop = element.scrollHeight; });
    await capture('cept-scores-review-mobile.png');
    await page.getByRole('button', { name: 'Cancel', exact: true }).focus(); await page.keyboard.press('Tab');
    assert.equal(await page.getByRole('dialog').evaluate(element => element.contains(globalThis.document.activeElement)), true);
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Save 3 matched & download', exact: true }).click();
    const download = await pending; const target = path.join(folder, 'clean-scores.xlsx'); await download.saveAs(target);
    await page.getByRole('heading', { name: 'Scores saved. Your file is ready.', exact: true }).waitFor();
    const book = XLSX.read(await readFile(target), { type: 'buffer' }); const rows = XLSX.utils.sheet_to_json(book.Sheets[book.SheetNames[0]], { header: 1 });
    assert.equal(rows[1][0], '00120'); assert.equal(rows[1][1], 'Student'); assert.equal(rows[1][2], 'Written'); assert.equal(rows.length, 5);
    assert.equal((await prisma.student.findUnique({ where: { registrationNumber: '00120-R1' } })).score, 85);
    assert.equal((await prisma.student.findUnique({ where: { registrationNumber: '00120' } })).score, 70);
    assert.equal(await prisma.student.count({ where: { registrationNumber: '00999-R9' } }), 0);
    await page.getByRole('button', { name: 'Done', exact: true }).click();
    await page.getByRole('button', { name: 'Upload Scores', exact: true }).first().click();
    await page.getByRole('heading', { name: 'Check scores', exact: true }).waitFor(); await page.keyboard.press('Escape'); await page.locator('dialog.review-dialog[open]').waitFor({ state: 'hidden' }); assert.equal(await page.locator('dialog.review-dialog[open]').count(), 0);
    assert.deepEqual(errors, [], errors.join('\n'));
  } finally {
    if (browser) await browser.close();
    if (server) await new Promise(resolve => server.close(resolve));
    if (prisma) await prisma.$disconnect();
    await rm(folder, { recursive: true, force: true });
  }
});
